using System.Net;
using DnaEntropyGraph.Core.Cloud;
using Shouldly;
using Xunit;

namespace DnaEntropyGraph.Cloud.Tests.Rest;

/// <summary>Allocation is measured process-wide, so nothing else may run beside these tests.</summary>
[CollectionDefinition(Name, DisableParallelization = true)]
public sealed class StreamingDownloadCollection
{
    public const string Name = "streaming-download-allocation";
}

/// <summary>
/// Issue #588: a result file (a probability matrix can be hundreds of MB) is downloaded from the real gateway straight to a file
/// without ever holding the object in memory. The body is generated by the scripted HTTP handler, never stored, so the only way the
/// process allocates object-sized memory is the gateway buffering it.
/// </summary>
[Collection(StreamingDownloadCollection.Name)]
public class GoogleStorageStreamingDownloadTests : IDisposable
{
    private const string ObjectPath = "/storage/v1/b/deg-b/o/jobs%2Fj1%2Foutput%2Fprobs.npy";
    private const string Key = "jobs/j1/output/probs.npy";
    private const long BigBytes = 256L * 1024 * 1024;

    private readonly string _folder = Path.Combine(Path.GetTempPath(), "deg-588-" + Guid.NewGuid().ToString("N"));

    public GoogleStorageStreamingDownloadTests() => Directory.CreateDirectory(_folder);

    public void Dispose()
    {
        try
        {
            Directory.Delete(_folder, recursive: true);
        }
        catch (IOException)
        {
        }
    }

    private static GoogleGatewayHarness NewRig() => new();

    private string Target => Path.Combine(_folder, "probs.npy.part");

    private static byte At(long i) => (byte)((i * 31) + (i >> 20));

    /// <summary>A body of <paramref name="length"/> generated bytes that fails like a dropped connection after <paramref name="failAfter"/> of them.</summary>
    private sealed class GeneratedContent(long length, long? failAfter = null) : HttpContent
    {
        public Func<long, Task>? OnProgress { get; init; }

        protected override Task SerializeToStreamAsync(Stream stream, TransportContext? context) => CreateContentReadStreamAsync().ContinueWith(async t => await t.Result.CopyToAsync(stream)).Unwrap();

        protected override Task<Stream> CreateContentReadStreamAsync() => Task.FromResult<Stream>(new GeneratedStream(length, failAfter, OnProgress));

        protected override bool TryComputeLength(out long l)
        {
            l = length;
            return true;
        }
    }

    private sealed class GeneratedStream(long length, long? failAfter, Func<long, Task>? onProgress) : Stream
    {
        private long _position;

        public override bool CanRead => true;

        public override bool CanSeek => false;

        public override bool CanWrite => false;

        public override long Length => length;

        public override long Position
        {
            get => _position;
            set => throw new NotSupportedException();
        }

        public override int Read(byte[] buffer, int offset, int count) => Read(buffer.AsSpan(offset, count));

        public override int Read(Span<byte> buffer)
        {
            if (failAfter is { } limit && _position >= limit)
            {
                throw new IOException("The connection dropped while the body was being read.");
            }

            var n = (int)Math.Min(buffer.Length, Math.Min(length - _position, 65536));
            for (var i = 0; i < n; i++)
            {
                buffer[i] = At(_position + i);
            }

            _position += n;
            return n;
        }

        public override async ValueTask<int> ReadAsync(Memory<byte> buffer, CancellationToken cancellationToken = default)
        {
            cancellationToken.ThrowIfCancellationRequested();
            if (onProgress is not null)
            {
                await onProgress(_position).ConfigureAwait(false);
                cancellationToken.ThrowIfCancellationRequested();
            }

            return Read(buffer.Span);
        }

        public override Task<int> ReadAsync(byte[] buffer, int offset, int count, CancellationToken cancellationToken) => ReadAsync(buffer.AsMemory(offset, count), cancellationToken).AsTask();

        public override void Flush()
        {
        }

        public override long Seek(long offset, SeekOrigin origin) => throw new NotSupportedException();

        public override void SetLength(long value) => throw new NotSupportedException();

        public override void Write(byte[] buffer, int offset, int count) => throw new NotSupportedException();
    }

    private static HttpResponseMessage Ok(HttpContent content)
    {
        content.Headers.ContentType = new System.Net.Http.Headers.MediaTypeHeaderValue("application/octet-stream");
        return new HttpResponseMessage(HttpStatusCode.OK) { Content = content };
    }

    private static async Task AssertGeneratedAsync(string path, long length)
    {
        new FileInfo(path).Length.ShouldBe(length);
        await using var stream = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.Read, 81920, useAsync: true);
        var buffer = new byte[81920];
        long pos = 0;
        int read;
        while ((read = await stream.ReadAsync(buffer, TestContext.Current.CancellationToken)) > 0)
        {
            for (var i = 0; i < read; i++)
            {
                if (buffer[i] != At(pos + i))
                {
                    throw new ShouldAssertException($"byte {pos + i} differs");
                }
            }

            pos += read;
        }

        pos.ShouldBe(length);
    }

    [Fact]
    public async Task A_256_MB_object_is_downloaded_to_the_file_without_the_process_allocating_object_sized_memory()
    {
        var rig = NewRig();
        rig.Handler.Calls(HttpMethod.Get, ObjectPath, _ => Task.FromResult(Ok(new GeneratedContent(BigBytes))));

        GC.Collect();
        var before = GC.GetTotalAllocatedBytes(precise: true);
        var found = await rig.Gateways.Storage.TryDownloadToFileAsync("deg-b", Key, Target, CancellationToken.None);
        var allocated = GC.GetTotalAllocatedBytes(precise: true) - before;

        found.ShouldBeTrue();
        allocated.ShouldBeLessThan(BigBytes / 8, $"downloading {BigBytes} bytes allocated {allocated}: the gateway buffered the object");
        await AssertGeneratedAsync(Target, BigBytes);
    }

    [Fact]
    public async Task A_404_answers_false_and_leaves_no_file()
    {
        var rig = NewRig();
        rig.Handler.Returns(HttpMethod.Get, ObjectPath, 404, "{\"error\":{\"code\":404,\"message\":\"No such object\",\"status\":\"NOT_FOUND\"}}");

        (await rig.Gateways.Storage.TryDownloadToFileAsync("deg-b", Key, Target, CancellationToken.None)).ShouldBeFalse();

        File.Exists(Target).ShouldBeFalse();
    }

    [Fact]
    public async Task A_403_throws_the_permission_error_and_leaves_no_file()
    {
        var rig = NewRig();
        rig.Handler.Returns(HttpMethod.Get, ObjectPath, 403, "{\"error\":{\"code\":403,\"message\":\"user@example.com does not have storage.objects.get access to the Google Cloud Storage object. Permission 'storage.objects.get' denied on resource (or it may not exist).\",\"status\":\"PERMISSION_DENIED\"}}");

        var ex = await Should.ThrowAsync<CloudOperationException>(() => rig.Gateways.Storage.TryDownloadToFileAsync("deg-b", Key, Target, CancellationToken.None));

        ex.Kind.ShouldBe(CloudErrorKind.Permission);
        File.Exists(Target).ShouldBeFalse();
    }

    [Fact]
    public async Task A_connection_that_drops_part_way_leaves_no_partial_file()
    {
        var rig = NewRig();
        for (var i = 0; i < 6; i++)
        {
            rig.Handler.Calls(HttpMethod.Get, ObjectPath, _ => Task.FromResult(Ok(new GeneratedContent(8 * 1024 * 1024, failAfter: 3 * 1024 * 1024))));
        }

        await Should.ThrowAsync<Exception>(() => rig.Gateways.Storage.TryDownloadToFileAsync("deg-b", Key, Target, CancellationToken.None));

        File.Exists(Target).ShouldBeFalse("a failed download must not leave its partial behind");
    }

    [Fact]
    public async Task A_cancel_part_way_leaves_no_partial_file()
    {
        var rig = NewRig();
        using var cts = new CancellationTokenSource();
        rig.Handler.Calls(HttpMethod.Get, ObjectPath, _ => Task.FromResult(Ok(new GeneratedContent(64 * 1024 * 1024)
        {
            OnProgress = pos =>
            {
                if (pos > 1024 * 1024)
                {
                    cts.Cancel();
                }

                return Task.CompletedTask;
            },
        })));

        await Should.ThrowAsync<OperationCanceledException>(() => rig.Gateways.Storage.TryDownloadToFileAsync("deg-b", Key, Target, cts.Token));

        File.Exists(Target).ShouldBeFalse("a cancelled download must not leave its partial behind");
    }

    [Fact]
    public async Task A_small_object_arrives_intact()
    {
        var rig = NewRig();
        rig.Handler.Calls(HttpMethod.Get, ObjectPath, _ => Task.FromResult(Ok(new GeneratedContent(1234567))));

        (await rig.Gateways.Storage.TryDownloadToFileAsync("deg-b", Key, Target, CancellationToken.None)).ShouldBeTrue();

        await AssertGeneratedAsync(Target, 1234567);
    }
}
